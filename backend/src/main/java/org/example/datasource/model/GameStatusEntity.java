package org.example.datasource.model;

/**
 * Перечисление возможных состояний игровой сессии в слое данных.
 * <p>
 * Используется для фиксации текущего этапа игры и определения победителя
 * при сохранении в хранилище.
 */
public enum GameStatusEntity {

    /** * Ожидание игроков. 
     * Игра создана, но второй участник (или компьютер) еще не подключен. 
     */
    WAITING_FOR_PLAYERS,

    /** Ход игрока. 
     * Игра началась, оба участника подключены, и сейчас ходит один из игроков.
     */
    PLAYER_TURN,

    /** Завершение игры: ничья (свободных ячеек не осталось, победитель не определен). */
    DRAW,

    /** Победа конкретного игрока. */
    VICTORY
}