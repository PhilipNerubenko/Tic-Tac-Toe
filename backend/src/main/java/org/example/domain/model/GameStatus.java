package org.example.domain.model;

/**
 * Статус игровой сессии в бизнес-логике приложения.
 * <p>
 * Отражает текущее состояние игрового процесса и фиксирует финальный результат.
 */
public enum GameStatus {

    /** * Ожидание игроков. 
     * Игра создана, но второй участник (или компьютер) еще не подключен. 
     */
    WAITING_FOR_PLAYERS,

    /** Ход игрока. 
     * Игра началась, оба участника подключены, и сейчас ходит один из игроков.
     */
    PLAYER_TURN,

    /** Завершение игры: ничья (свободных ячеек не осталось, победитель не определен). */
    DRAW,

    /** Победа конкретного игрока. */
    VICTORY
}