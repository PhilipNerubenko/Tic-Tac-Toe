package org.example.web.model;

/**
 * Перечисление статусов игры для веб-интерфейса (API).
 * <p>
 * Эти значения передаются клиенту в формате JSON и используются
 * для отображения результата игры на стороне пользователя.
 */
public enum GameStatusDTO {

    /** * Ожидание игроков. 
     * Игра создана, но второй участник (или компьютер) еще не подключен. 
     */
    WAITING_FOR_PLAYERS,

    /** Ход игрока. 
     * Игра началась, оба участника подключены, и сейчас ходит один из игроков.
     */
    PLAYER_TURN,

    /** Завершение игры: ничья (свободных ячеек не осталось, победитель не определен). */
    DRAW,

    /** Победа конкретного игрока. */
    VICTORY
}